#!/usr/bin/env python3
"""
Convert extracted Wacky Panda 16kHz 16-bit mono WAV files in assets/audio/
into a PROGMEM C++ header (src/WackyPandaAudio.h) for direct I2S playback.
"""
import os
import struct
import wave

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AUDIO_DIR = os.path.join(ROOT, "assets", "audio")
OUT_HEADER = os.path.join(ROOT, "src", "WackyPandaAudio.h")

CLIPS = [
    ("sfx_intro.wav",        "SFX_PCM_INTRO"),
    ("sfx_spin.wav",         "SFX_PCM_SPIN"),
    ("sfx_stop.wav",         "SFX_PCM_STOP"),
    ("sfx_win_redpanda.wav", "SFX_PCM_WIN_REDPANDA"),
    ("sfx_win_small.wav",    "SFX_PCM_WIN_SMALL"),
    ("sfx_win_big.wav",      "SFX_PCM_WIN_BIG"),
]


def main():
    lines = [
        "#pragma once",
        "#include <Arduino.h>",
        "#include <pgmspace.h>",
        "",
        "// Authentic Wacky Panda (Microgaming) 16,000 Hz 16-bit mono PCM audio clips",
        "// Auto-generated by scripts/generate_audio_header.py from assets/audio/*.wav",
        "",
        "static constexpr uint32_t WACKY_AUDIO_SAMPLE_RATE = 16000;",
        "",
    ]

    total_bytes = 0
    for filename, sym in CLIPS:
        path = os.path.join(AUDIO_DIR, filename)
        with wave.open(path, "rb") as w:
            assert w.getnchannels() == 1, f"{filename} must be mono"
            assert w.getsampwidth() == 2, f"{filename} must be 16-bit"
            assert w.getframerate() == 16000, f"{filename} must be 16000 Hz"
            n = w.getnframes()
            raw = w.readframes(n)
            samples = struct.unpack(f"<{n}h", raw)

        total_bytes += n * 2
        lines.append(f"// {filename}: {n} samples ({n / 16000.0:.2f}s, {n * 2 / 1024.0:.1f} KB)")
        lines.append(f"static constexpr size_t {sym}_LEN = {n};")
        lines.append(f"static const int16_t {sym}[{n}] PROGMEM = {{")

        row = []
        for i, s in enumerate(samples):
            row.append(str(s))
            if len(row) == 16 or i == n - 1:
                lines.append("  " + ",".join(row) + ("," if i < n - 1 else ""))
                row = []
        lines.append("};")
        lines.append("")

    with open(OUT_HEADER, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    print(f"Generated {OUT_HEADER} ({total_bytes / 1024.0:.1f} KB total PCM data)")


if __name__ == "__main__":
    main()
